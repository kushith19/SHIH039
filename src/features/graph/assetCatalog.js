export const MAX_PACKETS_PER_SECOND_FOR_VIS = 100_000

const HANDLES = {
  in: ['top', 'left', 'right', 'bottom'],
  out: ['top', 'left', 'right', 'bottom'],
}

function criticalityFromTrust(trust) {
  const t = Number(trust)
  if (!Number.isFinite(t)) return 'medium'
  if (t >= 90) return 'critical'
  if (t >= 75) return 'high'
  if (t >= 55) return 'medium'
  return 'low'
}

function sector({
  type,
  title,
  domain,
  Icon,
  pps,
  http,
  files = 0,
  logins = 0,
  trust,
  criticality,
}) {
  return {
    type,
    title,
    domain,
    defaultPacketsPerSecond: pps,
    defaultHttpRequestsPerMin: http,
    defaultFilesDownloaded: files,
    defaultFailedLoginsPerMin: logins,
    intrinsicTrust: trust,
    defaultCriticality: criticality ?? criticalityFromTrust(trust),
    Icon,
    handles: HANDLES,
  }
}

