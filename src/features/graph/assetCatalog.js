export function getAssetsGroupedByDomain() {
  const groups = ASSET_DOMAINS.map((domain) => ({
    domain,
    assets: assetCatalog.filter((a) => a.domain === domain),
  }))
  return groups.filter((g) => g.assets.length > 0)
}
